-- Loreleaf schema. Run in Supabase SQL editor.
create extension if not exists pg_trgm;

create table if not exists profiles (
  id uuid primary key references auth.users on delete cascade,
  display_name text, handle text unique, avatar_url text,
  ui_lang text default 'en', content_langs text[] default '{en}',
  birth_year int, age_status text default 'unverified' check (age_status in ('unverified','verified','denied')),
  favorite_genres text[] default '{}', daily_goal int default 20,
  theme text default 'midnight', accent text default '#8b9cff',
  role text default 'user' check (role in ('user','moderator','admin')),
  suspended boolean default false, created_at timestamptz default now()
);
create table if not exists titles (
  id bigint generated by default as identity (start with 1000000) primary key,
  title text not null, author text, format text check (format in ('novel','manhwa','manga')),
  genres text[] default '{}', tags text[] default '{}', warnings text[] default '{}',
  lang text default 'en', status text default 'ongoing', year int, rating real default 0, votes int default 0,
  popularity real default 0, velocity real default 0, chapters_count int default 0,
  mature boolean default false, hue int default 0, synopsis text, created_at timestamptz default now()
);
create table if not exists chapters (
  id bigint generated always as identity primary key, title_id bigint references titles on delete cascade,
  number int not null, title text, content text, pages jsonb, version text default 'official',
  published_at timestamptz default now(), unique (title_id, number, version)
);
create table if not exists user_library (
  user_id uuid references profiles on delete cascade, title_id bigint,
  status text check (status in ('reading','plan','completed','hold','dropped')), updated_at timestamptz default now(),
  primary key (user_id, title_id)
);
create table if not exists reading_progress (
  user_id uuid references profiles on delete cascade, title_id bigint, chapter int default 1, position real default 0,
  updated_at timestamptz default now(), primary key (user_id, title_id)
);
create table if not exists reading_streaks (
  user_id uuid references profiles on delete cascade, day date, minutes real default 0, primary key (user_id, day)
);
create table if not exists highlights_notes (
  id uuid primary key default gen_random_uuid(), user_id uuid references profiles on delete cascade,
  title_id bigint, chapter int, kind text default 'hl', text text, note text, created_at timestamptz default now()
);
create table if not exists reviews (
  id uuid primary key default gen_random_uuid(), user_id uuid references profiles on delete cascade,
  title_id bigint, rating int check (rating between 1 and 5), body text, spoiler boolean default false,
  hidden boolean default false, created_at timestamptz default now()
);
create table if not exists news_posts (
  id uuid primary key default gen_random_uuid(), title text not null, body text, category text,
  published boolean default true, author uuid, created_at timestamptz default now()
);
create table if not exists site_settings (key text primary key, value jsonb not null);
create table if not exists catalog_sync_logs (
  id bigint generated always as identity primary key, source text, status text, imported int default 0, message text, created_at timestamptz default now()
);
create table if not exists collections (
  id uuid primary key default gen_random_uuid(), user_id uuid references profiles on delete cascade, name text, title_ids bigint[] default '{}', created_at timestamptz default now()
);
create table if not exists chapter_polls (
  id uuid primary key default gen_random_uuid(), title_id bigint, chapter int, question text, options jsonb, votes jsonb default '{}', created_at timestamptz default now()
);

-- Indexes for 100k+ catalogs
create index if not exists titles_trgm on titles using gin (title gin_trgm_ops);
create index if not exists titles_author_trgm on titles using gin (author gin_trgm_ops);
create index if not exists titles_genres on titles using gin (genres);
create index if not exists titles_warnings on titles using gin (warnings);
create index if not exists titles_fmt_rating on titles (format, rating desc);
create index if not exists titles_velocity on titles (velocity desc);
create index if not exists titles_popularity on titles (popularity desc);
create index if not exists titles_year on titles (year desc);
create index if not exists titles_mature on titles (mature);
create index if not exists chapters_title on chapters (title_id, number);
create index if not exists progress_user on reading_progress (user_id, updated_at desc);
create index if not exists reviews_title on reviews (title_id);

-- Helpers
create or replace function is_admin() returns boolean language sql security definer stable as
$$ select exists (select 1 from profiles where id = auth.uid() and role = 'admin') $$;
create or replace function is_mod() returns boolean language sql security definer stable as
$$ select exists (select 1 from profiles where id = auth.uid() and role in ('admin','moderator')) $$;

create or replace function handle_new_user() returns trigger language plpgsql security definer as $$
begin
  insert into profiles (id, display_name) values (new.id, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email,'@',1)))
  on conflict do nothing; return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function handle_new_user();

-- Users cannot escalate their own role / age status / suspension
create or replace function protect_profile() returns trigger language plpgsql security definer as $$
begin
  if not is_admin() then new.role := old.role; new.age_status := old.age_status; new.suspended := old.suspended; end if;
  return new;
end $$;
drop trigger if exists protect_profile_t on profiles;
create trigger protect_profile_t before update on profiles for each row execute function protect_profile();

-- RLS
alter table profiles enable row level security; alter table titles enable row level security; alter table chapters enable row level security;
alter table user_library enable row level security; alter table reading_progress enable row level security; alter table reading_streaks enable row level security;
alter table highlights_notes enable row level security; alter table reviews enable row level security; alter table news_posts enable row level security;
alter table site_settings enable row level security; alter table catalog_sync_logs enable row level security; alter table collections enable row level security;
alter table chapter_polls enable row level security;

create policy "profiles read own or admin" on profiles for select using (id = auth.uid() or is_admin());
create policy "profiles insert own" on profiles for insert with check (id = auth.uid());
create policy "profiles update own or admin" on profiles for update using (id = auth.uid() or is_admin());
create policy "profiles delete admin" on profiles for delete using (is_admin());

create policy "titles public read" on titles for select using (true);
create policy "titles admin write" on titles for all using (is_admin()) with check (is_admin());
create policy "chapters public read" on chapters for select using (true);
create policy "chapters admin write" on chapters for all using (is_admin()) with check (is_admin());

create policy "library own" on user_library for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "progress own" on reading_progress for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "streaks own" on reading_streaks for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "notes own" on highlights_notes for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "collections own" on collections for all using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "reviews read" on reviews for select using (not hidden or user_id = auth.uid() or is_mod());
create policy "reviews insert own" on reviews for insert with check (user_id = auth.uid());
create policy "reviews update own or mod" on reviews for update using (user_id = auth.uid() or is_mod());
create policy "reviews delete own or mod" on reviews for delete using (user_id = auth.uid() or is_mod());

create policy "news read published" on news_posts for select using (published or is_admin());
create policy "news admin write" on news_posts for all using (is_admin()) with check (is_admin());
create policy "settings read" on site_settings for select using (true);
create policy "settings admin write" on site_settings for all using (is_admin()) with check (is_admin());
create policy "sync logs admin" on catalog_sync_logs for all using (is_admin()) with check (is_admin());
create policy "polls read" on chapter_polls for select using (true);
create policy "polls admin write" on chapter_polls for all using (is_mod()) with check (is_mod());

